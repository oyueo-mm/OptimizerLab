import test from 'node:test';
import assert from 'node:assert/strict';
test('the application boots into the four-card home without a browser dependency',async()=>{
  const root={innerHTML:''};
  const handlers={};
  const overlay={hidden:true,querySelector:()=>({focus:()=>{}})};
  const toggle={attributes:{},setAttribute(k,v){this.attributes[k]=v;},focus:()=>{}};
  globalThis.window={matchMedia:()=>({matches:true}),addEventListener:()=>{},scrollTo:()=>{}};
  globalThis.document={title:'',querySelector:s=>s==='#app'?root:s==='[data-settings-overlay]'?overlay:s==='[data-settings-toggle]'?toggle:null,querySelectorAll:()=>[],addEventListener:(name,handler)=>{handlers[name]=handler;}};
  globalThis.requestAnimationFrame=()=>0;
  await import('../src/app.js');
  assert.match(root.innerHTML,/OptimizerLab/);
  assert.doesNotMatch(root.innerHTML,/EXPLORE|12 optimizers|Optimization, visualized|공을 놓고, 움직임을 관찰하세요/);
  assert.match(root.innerHTML,/data-preview="sgd"/);
  assert.match(root.innerHTML,/data-preview="momentum"/);
  assert.match(root.innerHTML,/data-preview="adamw"/);
  assert.match(root.innerHTML,/data-preview="adam"/);
  assert.match(root.innerHTML,/data-nav="experiment"/);
  assert.match(root.innerHTML,/data-nav="compare"/);
  const press=(attributes,dataset={})=>handlers.click({target:{closest:()=>({dataset,hasAttribute:(name)=>attributes.includes(name)})}});
  press([],{nav:'experiment'});
  assert.match(root.innerHTML,/data-settings-toggle/);
  assert.match(root.innerHTML,/data-settings-overlay hidden/);
  assert.match(root.innerHTML,/data-fullscreen/);
  press(['data-settings-toggle']);
  assert.equal(overlay.hidden,false,'settings drawer opens without destroying the canvas');
  assert.equal(toggle.attributes['aria-expanded'],'true');
  press(['data-settings-close']);
  assert.equal(overlay.hidden,true,'settings drawer closes');
  assert.equal(toggle.attributes['aria-expanded'],'false');
});
