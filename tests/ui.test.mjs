import test from 'node:test';
import assert from 'node:assert/strict';
test('the application boots into the four-card home without a browser dependency',async()=>{
  const root={innerHTML:''};
  const handlers={};
  const overlay={hidden:true,querySelector:()=>({focus:()=>{}})};
  const toggle={attributes:{},setAttribute(k,v){this.attributes[k]=v;},focus:()=>{}};
  const comparePicker={open:true};
  const compareSummary={textContent:''};
  const makePill=id=>({dataset:{compare:id},attributes:{},disabled:false,style:{},classList:{toggle:()=>{}},setAttribute(k,v){this.attributes[k]=v;},querySelector:k=>k==='.compare-check'?{textContent:''}:k==='.bullet'?{style:{}}:null});
  const comparePills=['sgd','lion','adam','momentum','adamw','nesterov'].map(makePill);
  globalThis.window={matchMedia:()=>({matches:true}),addEventListener:()=>{},scrollTo:()=>{}};
  globalThis.document={title:'',querySelector:s=>s==='#app'?root:s==='[data-settings-overlay]'?overlay:s==='[data-settings-toggle]'?toggle:s==='.compare-choices summary'?compareSummary:s==='.compare-choices'?comparePicker:null,querySelectorAll:s=>s==='[data-compare]'?comparePills:[],addEventListener:(name,handler)=>{handlers[name]=handler;}};
  globalThis.requestAnimationFrame=()=>0;
  await import('../src/app.js');
  assert.match(root.innerHTML,/OptimizerLab/);
  assert.doesNotMatch(root.innerHTML,/EXPLORE|12 optimizers|Optimization, visualized|공을 놓고, 움직임을 관찰하세요/);
  assert.match(root.innerHTML,/data-preview="sgd"/);
  assert.match(root.innerHTML,/data-preview="momentum"/);
  assert.match(root.innerHTML,/data-preview="adamw"/);
  assert.match(root.innerHTML,/data-preview="adam"/);
  assert.match(root.innerHTML,/data-nav="experiment"/);
  assert.match(root.innerHTML,/data-nav="compare"/);
  const press=(attributes,dataset={})=>handlers.click({target:{closest:()=>({dataset,hasAttribute:(name)=>attributes.includes(name)})}});
  press([],{nav:'experiment'});
  assert.match(root.innerHTML,/class="page workspace-page"/);
  assert.match(root.innerHTML,/class="workspace-stage"/);
  assert.doesNotMatch(root.innerHTML,/class="page-header"|class="topbar"|class="canvas-hint"/);
  assert.ok(root.innerHTML.indexOf('class="playbar"')<root.innerHTML.indexOf('class="workspace-extras"'),'playback controls must remain in the first viewport');
  assert.match(root.innerHTML,/data-settings-toggle/);
  assert.match(root.innerHTML,/data-settings-overlay hidden/);
  assert.match(root.innerHTML,/data-fullscreen/);
  press(['data-settings-toggle']);
  assert.equal(overlay.hidden,false,'settings drawer opens without destroying the canvas');
  assert.equal(toggle.attributes['aria-expanded'],'true');
  press(['data-settings-close']);
  assert.equal(overlay.hidden,true,'settings drawer closes');
  assert.equal(toggle.attributes['aria-expanded'],'false');
  press([],{open:'sgd'});
  assert.match(root.innerHTML,/class="visual-title">SGD<\/span>/);
  assert.equal((root.innerHTML.match(/class="visual-title"/g)||[]).length,1,'detail page shows one title');
  assert.doesNotMatch(root.innerHTML,/class="page-header"|class="topbar"/);
  press([],{nav:'compare'});
  assert.match(root.innerHTML,/class="compare-choices"/);
  assert.match(root.innerHTML,/비교 알고리즘 선택 \(6\/6\)/);
  assert.match(root.innerHTML,/disabled class="compare-pill/,'unselected optimizers disabled at cap');
  assert.equal((root.innerHTML.match(/class="legend-item"/g)||[]).length,6,'six trajectories appear in legend');
  assert.ok(root.innerHTML.indexOf('class="playbar"')<root.innerHTML.indexOf('class="compare-choices"'),'comparison choices appear beneath the visible canvas');
  const initialCompareHtml=root.innerHTML;
  comparePicker.open=true;
  press([],{compare:'sgd'});
  assert.equal(root.innerHTML,initialCompareHtml,'choosing first optimizer does not recreate the selector or canvas');
  assert.equal(comparePicker.open,true,'comparison selector stays expanded');
  assert.match(compareSummary.textContent,/5\/6/);
  press([],{compare:'lion'});
  assert.equal(root.innerHTML,initialCompareHtml,'subsequent selections do not recreate the page');
  assert.equal(comparePicker.open,true);
  assert.match(compareSummary.textContent,/6\/6/);
  press(['data-compare-cancel']);
  assert.equal(comparePicker.open,false,'cancel closes selection');
  assert.equal(comparePills.find(p=>p.dataset.compare==='sgd').attributes['aria-pressed'],'true','cancel restores original selection');
  assert.equal(comparePills.find(p=>p.dataset.compare==='lion').attributes['aria-pressed'],'false','cancel discards draft selections');
  comparePicker.open=true;
  press([],{compare:'sgd'});
  press([],{compare:'lion'});
  press(['data-compare-apply']);
  assert.match(root.innerHTML,/data-compare="lion" aria-pressed="true"/,'Apply saves the new selection');
  assert.match(root.innerHTML,/data-compare="sgd" aria-pressed="false"/,'Apply removes the deselected optimizer');
  assert.match(root.innerHTML,/비교 알고리즘 선택 \(6\/6\)/);
  press([],{nav:'experiment'});
  const before=root.innerHTML;
  press(['data-settings-toggle']);
  handlers.change({target:{matches:q=>q==='select[data-setting]',dataset:{setting:'optimizer'},value:'rmsprop'}});
  handlers.change({target:{matches:q=>q==='select[data-setting]',dataset:{setting:'landscape'},value:'faultMaze'}});
  assert.equal(root.innerHTML,before,'draft selections do not rerender or change the simulation');
  assert.equal(overlay.hidden,false,'drawer stays open after selection');
  press(['data-settings-close']);
  press(['data-settings-toggle']);
  assert.equal(overlay.hidden,false);
  press(['data-settings-apply']);
  assert.match(root.innerHTML,/class="visual-title">실험실<\/span>/,'cancelled changes never changed the page');
  assert.match(root.innerHTML,/class="visual-landscape">물결 계곡<\/span>/,'cancelled map remains unchanged');
  press(['data-settings-toggle']);
  handlers.change({target:{matches:q=>q==='select[data-setting]',dataset:{setting:'optimizer'},value:'rmsprop'}});
  handlers.change({target:{matches:q=>q==='select[data-setting]',dataset:{setting:'landscape'},value:'faultMaze'}});
  press(['data-settings-apply']);
  assert.match(root.innerHTML,/class="visual-landscape">단층 미로<\/span>/,'Apply commits the selected landscape');
  assert.match(root.innerHTML,/value="rmsprop" selected/,'Apply commits the selected optimizer');
  assert.match(root.innerHTML,/data-settings-overlay hidden/,'drawer closes after Apply');
});
